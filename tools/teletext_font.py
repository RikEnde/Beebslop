"""Generate TeletextFont.kt from Bedstead's bedstead.c.

Usage: python3 -I tools/teletext_font.py path/to/bedstead.c > \
    bbc/src/commonMain/kotlin/beebslop/bbc/TeletextFont.kt

The input must be bedstead.c from Bedstead 3.261
(https://bjh21.me.uk/bedstead/), checked by its SHA-256 below.
"""
import hashlib
import re
import sys

BEDSTEAD_VERSION = "3.261"
BEDSTEAD_SHA256 = "432e8fe8b77cada259833170b4007494a2bc8584caeefcf8bebd385f5d4262b1"

# The English SAA5050 differs from the US ASCII SAA5055 at these codes. The
# replacement glyphs are the eleven Bedstead lists as "Extra characters found
# in the English (SAA5050) character set", plus '#' moved to &5F.
ENGLISH = {
    0x23: "sterling", 0x27: "quotesingle", 0x5B: "arrowleft", 0x5C: "onehalf",
    0x5D: "arrowright", 0x5E: "arrowup", 0x5F: "numbersign", 0x60: "emdash",
    0x7B: "onequarter", 0x7C: "dblverticalbar", 0x7D: "threequarters", 0x7E: "divide",
}

ENTRY = re.compile(r'\{"((?:\\[0-7]{2}){9})",\s*0x([0-9a-f]+),\s*"([^"]+)"')


def main(path):
    data = open(path, "rb").read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != BEDSTEAD_SHA256:
        sys.exit(f"{path}: SHA-256 {digest}, expected {BEDSTEAD_SHA256}")
    text = data.decode("utf-8")
    start = text.index("/* US ASCII (SAA5055) character set */")
    end = text.index("/* Extra characters found in the German (SAA5051) character set */")
    by_name = {}
    us = []
    for m in ENTRY.finditer(text, start, end):
        rows = [int(r, 8) for r in re.findall(r"\\([0-7]{2})", m.group(1))]
        by_name[m.group(3)] = rows
        if len(us) < 96:
            us.append((m.group(3), rows))
    if len(us) != 96 or us[0][0] != "space" or us[-1][0] != "filledbox":
        sys.exit("unexpected layout of the US ASCII table")
    glyphs = []
    for i, (name, rows) in enumerate(us):
        code = 0x20 + i
        if code in ENGLISH:
            name = ENGLISH[code]
            rows = by_name[name]
        glyphs.append((code, name, rows))

    out = sys.stdout
    out.write(f"""// SPDX-FileCopyrightText: 2009-2025 Ben Harris, Simon Tatham, Marnanel Thurman, Neil Williamson
// SPDX-License-Identifier: CC0-1.0 AND LicenseRef-CDPA-s55
//
// Generated by tools/teletext_font.py from bedstead.c in Bedstead {BEDSTEAD_VERSION}
// (https://bjh21.me.uk/bedstead/), SHA-256 {BEDSTEAD_SHA256}.
// Do not edit by hand.

package beebslop.bbc

/**
 * The English SAA5050's character shapes, codes `&20-&7F`, from Ben Harris's
 * Bedstead. Each glyph is 9 rows of 5 dots, top row first, bit 4 leftmost. In
 * the SAA5050's 6 by 10 cell the glyph sits one row down, below a blank row.
 *
 * Bedstead's authors dedicated their work to the public domain (CC0). The
 * shapes themselves are the SAA5050's; see LICENSES/LicenseRef-CDPA-s55.txt.
 */
internal object TeletextFont {{
    /** 96 glyphs of 9 rows each. */
    val rows: IntArray = intArrayOf(
""")
    for code, name, rows in glyphs:
        values = ", ".join(f"0x{r:02X}" for r in rows)
        out.write(f"        {values}, // &{code:02X} {name}\n")
    out.write("""    )
}
""")


if __name__ == "__main__":
    main(sys.argv[1])
